#!/usr/bin/env python3
"""Copies Groove Grabber's genres, styles and artist/song table into Song Savant, so both apps understand the same
words ("80s pop", "like Morgan Wallen", "Elevation Worship") and use the same style ids.

    python3 tools/sync_from_groove_grabber.py <path to the Groove-Grabber checkout>

Writes Source/core/MusicData.inc. Run it again whenever Groove Grabber's styles or artists change.
"""
import re, subprocess, sys, pathlib

gg = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "../Groove-Grabber")
styles_cpp = (gg / "Source/core/Styles.cpp").read_text(encoding="utf-8")
refs_cpp = (gg / "Source/core/References.cpp").read_text(encoding="utf-8")
try:
    commit = subprocess.run(["git", "-C", str(gg), "log", "-1", "--format=%h %s"], capture_output=True, text=True).stdout.strip()
except Exception:
    commit = "unknown"

eras = {"E60": "60s", "E70": "70s", "E80": "80s", "E90": "90s", "E2000": "2000s", "E2010": "2010s", "ENOW": "now"}
pattern = re.compile(r'style\s*\(\s*Genre::(\w+),\s*"([^"]+)",\s*"([^"]+)",\s*\{([^}]*)\},\s*\{([^}]*)\},\s*([\d.]+)', re.S)
rows = []
for genre, sid, name, kw, er, bpm in pattern.findall(styles_cpp):
    words = [w.strip().strip('"') for w in kw.split(",") if w.strip()]
    era_names = [eras[e.strip()] for e in er.split(",") if e.strip()]
    rows.append((genre, sid, name, "|".join(words), "|".join(era_names), bpm))
if len(rows) < 20:
    sys.exit("found only %d styles: has Styles.cpp changed shape?" % len(rows))

start = refs_cpp.index("const char* const table[] = {")
end = refs_cpp.index("};", start)
table = refs_cpp[start:end].split("{", 1)[1]
lines = [l.rstrip() for l in table.splitlines() if l.strip()]

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

out = ["// Generated by tools/sync_from_groove_grabber.py from Groove Grabber (%s). Don't edit by hand." % commit,
       "// Groove Grabber genre | style id | style name | keywords | eras | BPM", "",
       "static const StyleRow styleRows[] = {"]
for r in rows:
    out.append('    { "%s", "%s", "%s", "%s", "%s", %s },' % (r[0], esc(r[1]), esc(r[2]), esc(r[3]), r[4], r[5]))
out += ["};", "", "// Artists and songs: Name|alias|~alias = style era lead sound words ; ...   (@ = a song, \"Title / Artist\")",
        "static const char* const referenceRows[] = {"]
out += ["    " + l.strip() for l in lines]
out += ["};", ""]
dest = pathlib.Path(__file__).resolve().parent.parent / "Source/core/MusicData.inc"
dest.write_text("\n".join(out), encoding="utf-8")
print("wrote %s: %d styles, %d table lines" % (dest, len(rows), len(lines)))
